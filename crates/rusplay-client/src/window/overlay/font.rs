pub(super) fn glyph(character: char) -> Glyph {
    let upper = character.to_ascii_uppercase();

    GLYPHS
        .iter()
        .find(|(known, _)| *known == upper)
        .map_or(UNKNOWN, |(_, glyph)| *glyph)
}

pub(super) const fn lit(row: u8, column: usize) -> bool {
    (row >> (GLYPH_WIDTH - 1 - column)) & 1 == 1
}
